import com.tngtech.archunit.base.DescribedPredicate;
import com.tngtech.archunit.core.domain.JavaClass;
import com.tngtech.archunit.core.domain.JavaClasses;
import com.tngtech.archunit.core.importer.ClassFileImporter;
import com.tngtech.archunit.lang.ArchCondition;
import com.tngtech.archunit.lang.ArchRule;
import com.tngtech.archunit.lang.ConditionEvents;
import com.tngtech.archunit.lang.SimpleConditionEvent;
import org.junit.jupiter.api.Test;
import org.springframework.data.repository.CrudRepository;

import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.classes;
import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noClasses;
import static com.tngtech.archunit.library.dependencies.SlicesRuleDefinition.slices;

public class ArchitectureTest {

    private static final DescribedPredicate<JavaClass> NOT_LOMBOK_GENERATED =
            DescribedPredicate.describe("not generated by Lombok",
                    javaClass -> !javaClass.isAnnotatedWith("lombok.Generated"));

    private final JavaClasses classes = new ClassFileImporter()
            .importPackages("com.negociadororq..")
            .that(NOT_LOMBOK_GENERATED);

    // ==================== REGLAS DE DEPENDENCIA ====================

    @Test
    void domain_no_debe_depende_de_nadie() {
        ArchRule rule = noClasses()
                .that().resideInAPackage("..domain..")
                .should().dependOnClassesThat()
                .resideInAnyPackage("..application..", "..infrastructure..", "..web..");

        rule.check(classes);
    }

    @Test
    void application_solo_puede_depende_de_domain() {
        ArchRule rule = classes()
                .that().resideInAPackage("..application..")
                .should().onlyDependOnClassesThat()
                .resideInAnyPackage("..application..", "..domain..", "java..", "javax..", "jakarta..", "org.springframework..", "io.swagger.v3.oas..", "com.factoring.commons..");

        rule.check(classes);
    }

    @Test
    void infraestructura_solo_puede_depende_de_application_y_domain() {
        ArchRule rule = classes()
                .that().resideInAPackage("..infrastructure..")
                .should().onlyDependOnClassesThat()
                .resideInAnyPackage(
                        "..infrastructure..", "..application..", "..domain..",
                        "java..", "javax..", "jakarta..", "org.springframework..", "io.swagger.v3.oas..",
                        "com.factoring.commons..", "com.fasterxml.jackson..", "com.github.mustachejava..",
                        "io.jsonwebtoken..", "net.javacrumbs.shedlock..", "org.apache.kafka..",
                        "org.apache.pdfbox..", "org.slf4j..", "com.openhtmltopdf..", "org.bson..");

        rule.check(classes);
    }

    @Test
    void web_solo_puede_depende_de_application() {
        ArchRule rule = classes()
                .that().resideInAPackage("..web..")
                .should().onlyDependOnClassesThat()
                .resideInAnyPackage("..web..", "..application..", "..domain..", "java..", "jakarta..", "org.springframework..", "io.swagger.v3.oas..", "com.factoring.commons..");

        rule.check(classes);
    }

    // ==================== REGLAS DE NOMBRES Y ESTRUCTURA ====================

    @Test
    void controllers_deben_estar_en_web() {
        classes().that().haveNameMatching(".*Controller")
                .should().resideInAPackage("..web.controller..")
                .check(classes);
    }

    @Test
    void services_deben_estar_en_aplication_o_domain() {
        // Las clases que implementan UserDetailsService (Spring Security) llevan ese
        // sufijo por convención del framework, no por ser servicios de aplicación/dominio.
        classes().that().haveNameMatching(".*Service")
                .and().doNotImplement("org.springframework.security.core.userdetails.UserDetailsService")
                .should().resideInAnyPackage("..application.service..", "..domain..")
                .check(classes);
    }

    // ==================== REGLAS DE NO CICLOS Y ACOPLAMIENTO ====================

    @Test
    void no_deberia_haber_ciclos_entre_capas() {
        slices().matching("com.negociadororq.(*)..")
                .should().beFreeOfCycles()
                .check(classes);
    }

    @Test
    void domain_no_debe_usar_anotaciones_de_spring() {
        noClasses()
                .that().resideInAPackage("..domain..")
                .should().dependOnClassesThat()
                .haveNameMatching(".*(Spring|Autowired|Service|Repository|Controller).*")
                .check(classes);
    }

    @Test
    void impl_debe_implementar_interfaz() {
        classes().that().haveSimpleNameEndingWith("Impl")
                .should(new ArchCondition<JavaClass>("implementar al menos una interfaz") {
                    @Override
                    public void check(JavaClass javaClass, ConditionEvents events) {
                        if (javaClass.getInterfaces().isEmpty()) {
                            events.add(SimpleConditionEvent.violated(
                                    javaClass, javaClass.getName() + " no implementa ninguna interfaz"));
                        }
                    }
                })
                .check(classes);
    }

    @Test
    void controllers_no_dependen_de_impls() {
        noClasses().that().resideInAPackage("..web.controller..")
                .should().dependOnClassesThat().haveSimpleNameEndingWith("Impl")
                .check(classes);
    }

    @Test
    void kafka_no_depende_de_impls() {
        noClasses().that().resideInAPackage("..kafka..")
                .should().dependOnClassesThat().haveSimpleNameEndingWith("Impl")
                .check(classes);
    }

    @Test
    void kafka_no_depende_de_scheduler() {
        noClasses().that().resideInAPackage("..kafka..")
                .should().dependOnClassesThat().resideInAPackage("..scheduler..")
                .check(classes);
    }

    // ==================== REGLAS DE ARQUITECTURA HEXAGONAL REAL ====================
    // Mismas 3 reglas en los 10 backends (pipeline de arquitectura hexagonal): el
    // dominio no debe depender del framework de persistencia, la aplicación no debe
    // inyectar un repositorio de Spring Data directo (solo puertos propios), y nadie
    // fuera de infraestructura debe depender de un adaptador concreto.

    @Test
    void domain_no_debe_usar_anotaciones_de_persistencia() {
        noClasses()
                .that().resideInAPackage("..domain..")
                .should().dependOnClassesThat()
                .resideInAnyPackage("jakarta.persistence..", "org.springframework.data..")
                .check(classes);
    }

    @Test
    void application_no_debe_depender_de_repositorios_framework_directo() {
        noClasses()
                .that().resideInAPackage("..application..")
                .should().dependOnClassesThat()
                .areAssignableTo(CrudRepository.class)
                .check(classes);
    }

    @Test
    void nadie_fuera_de_infraestructura_debe_depender_de_adapters() {
        noClasses()
                .that().resideOutsideOfPackage("..infrastructure..")
                .should().dependOnClassesThat().haveSimpleNameEndingWith("Adapter")
                .check(classes);
    }
}